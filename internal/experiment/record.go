// Provenance records everything needed to reproduce a run.
//
// This is not bookkeeping for its own sake. A results table without provenance
// cannot be checked by anyone, including its author six months later: the
// question "was this figure generated before or after the burst calibration
// changed?" has to be answerable from the data file alone.
type Provenance struct {
	// GitCommit is the repository state the run was executed from, and GitDirty
	// records whether there were uncommitted changes. A dirty run is still
	// recorded, but it is marked, because its results cannot be reproduced from
	// the commit alone.
	GitCommit string `json:"git_commit"`
	GitDirty  bool   `json:"git_dirty"`

	ConfigName string `json:"config_name"`
	// ConfigHash is the content hash of the resolved configuration.
	ConfigHash string `json:"config_hash"`

	StartedAt  time.Time `json:"started_at"`
	FinishedAt time.Time `json:"finished_at"`
	DurationMS int64     `json:"duration_ms"`

	GoVersion string `json:"go_version"`
	OS        string `json:"os"`
	Arch      string `json:"arch"`

	// Tool version, so that results generated by different builds are separable.
	ToolVersion string `json:"tool_version"`

	CostModel string `json:"cost_model"`

	// Conditions and Records report the intended and actual row counts. A
	// mismatch means conditions were skipped, which must be visible.
	Conditions int `json:"conditions"`
	Records    int `json:"records"`
}

// Record is one row of experimental data: one condition, fully specified, with
// its inputs, the engine's output, and the ground-truth outcome.
//
// The schema is flat and self-describing so that it can be loaded directly into
// a dataframe without a join. Every column needed to group, filter or reproduce
// the row is present on the row itself.
type Record struct {
	// --- Condition identity ---
	Experiment string `json:"experiment"`
	RunID      string `json:"run_id"`

	WorkloadClass string `json:"workload_class"`
	WorkloadName  string `json:"workload_name"`
	Seed          int64  `json:"seed"`

	CPUStrategy        string  `json:"cpu_strategy"`
	MemoryStrategy     string  `json:"memory_strategy"`
	CPUSafetyFactor    float64 `json:"cpu_safety_factor"`
	MemorySafetyFactor float64 `json:"memory_safety_factor"`

	ObservationWindowHours float64 `json:"observation_window_hours"`
	EvaluationHorizonHours float64 `json:"evaluation_horizon_hours"`
	StepSeconds            float64 `json:"step_seconds"`

	PolicyID string `json:"policy_id"`

	// Ablation flags, recorded on every row so that an ablation run and a
	// baseline run can be concatenated into one dataframe and separated by
	// filtering rather than by filename convention.
	OOMProtectionEnabled bool `json:"oom_protection_enabled"`
	UsageExceedsEnabled  bool `json:"usage_exceeds_enabled"`
	FloorsEnabled        bool `json:"floors_enabled"`
	MinChangeEnabled     bool `json:"min_change_enabled"`
	RoundingEnabled      bool `json:"rounding_enabled"`
	UnifiedStrategy      bool `json:"unified_strategy"`

	// --- Declared configuration ---
	DeclaredCPUMilli    float64 `json:"declared_cpu_milli"`
	DeclaredMemoryBytes float64 `json:"declared_memory_bytes"`

	// --- Engine output ---
	CPUDecision            string  `json:"cpu_decision"`
	MemoryDecision         string  `json:"memory_decision"`
	CPURisk                string  `json:"cpu_risk"`
	MemoryRisk             string  `json:"memory_risk"`
	RecommendedCPUMilli    float64 `json:"recommended_cpu_milli"`
	RecommendedMemoryBytes float64 `json:"recommended_memory_bytes"`
	RawCPUMilli            float64 `json:"raw_cpu_milli"`
	RawMemoryBytes         float64 `json:"raw_memory_bytes"`
	CPUGates               string  `json:"cpu_gates"`
	MemoryGates            string  `json:"memory_gates"`

	// --- Observed statistics (what the engine saw: censored) ---
	ObservedCPUMeanMilli float64 `json:"observed_cpu_mean_milli"`
	ObservedCPUP95Milli  float64 `json:"observed_cpu_p95_milli"`
	ObservedCPUP99Milli  float64 `json:"observed_cpu_p99_milli"`
	ObservedCPUMaxMilli  float64 `json:"observed_cpu_max_milli"`
	ObservedCPUSamples   int     `json:"observed_cpu_samples"`
	ObservedMemMeanBytes float64 `json:"observed_memory_mean_bytes"`
	ObservedMemP95Bytes  float64 `json:"observed_memory_p95_bytes"`
	ObservedMemP99Bytes  float64 `json:"observed_memory_p99_bytes"`
	ObservedMemMaxBytes  float64 `json:"observed_memory_max_bytes"`

	// --- Ground truth (what the engine did not see) ---
	TrueCPUMeanMilli float64 `json:"true_cpu_mean_milli"`
	TrueCPUP95Milli  float64 `json:"true_cpu_p95_milli"`
	TrueCPUP99Milli  float64 `json:"true_cpu_p99_milli"`
	TrueCPUMaxMilli  float64 `json:"true_cpu_max_milli"`
	TrueMemMeanBytes float64 `json:"true_memory_mean_bytes"`
	TrueMemP95Bytes  float64 `json:"true_memory_p95_bytes"`
	TrueMemP99Bytes  float64 `json:"true_memory_p99_bytes"`
	TrueMemMaxBytes  float64 `json:"true_memory_max_bytes"`

	// --- Evaluation ---
	Metrics
	// Stability is populated only when the config requested recomputations.
	Stability *StabilityMetrics `json:"stability,omitempty"`
}

// Result is a complete experiment run: its provenance, its resolved
// configuration and every record.
type Result struct {
	Provenance Provenance `json:"provenance"`
	Config     Config     `json:"config"`
	Records    []Record   `json:"records"`
}

// ConfigHash is the content hash of a configuration, used to tie records to the
// specification that produced them.
func ConfigHash(c Config) string {
	b, err := json.Marshal(c)
	if err != nil {
		panic(fmt.Sprintf("marshal experiment config: %v", err))
	}
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:8])
}

// NewProvenance captures the environment at the start of a run.
func NewProvenance(c Config, toolVersion, gitCommit string, gitDirty bool, costModel string) Provenance {
	return Provenance{
		GitCommit:   gitCommit,
		GitDirty:    gitDirty,
		ConfigName:  c.Name,
		ConfigHash:  ConfigHash(c),
		StartedAt:   time.Now().UTC(),
		GoVersion:   runtime.Version(),
		OS:          runtime.GOOS,
		Arch:        runtime.GOARCH,
		ToolVersion: toolVersion,
		CostModel:   costModel,
		Conditions:  c.Conditions(),
	}
}

// gatesString joins gate IDs for the flat record schema.
func gatesString(gs []string) string {
	if len(gs) == 0 {
		return ""
	}
	out := gs[0]
	for _, g := range gs[1:] {
		out += "|" + g
	}
	return out
}

// fillObserved copies the statistics the engine actually saw into the record.
func (r *Record) fillObserved(cr model.ContainerRecommendation) {
	r.ObservedCPUMeanMilli = cr.CPU.Stats.Mean
	r.ObservedCPUP95Milli = cr.CPU.Stats.P95
	r.ObservedCPUP99Milli = cr.CPU.Stats.P99
	r.ObservedCPUMaxMilli = cr.CPU.Stats.Max
	r.ObservedCPUSamples = cr.CPU.Stats.Samples
	r.ObservedMemMeanBytes = cr.Memory.Stats.Mean
	r.ObservedMemP95Bytes = cr.Memory.Stats.P95
	r.ObservedMemP99Bytes = cr.Memory.Stats.P99
	r.ObservedMemMaxBytes = cr.Memory.Stats.Max
}

// fillGroundTruth copies the demand envelope the engine never saw.
func (r *Record) fillGroundTruth(gt simulator.GroundTruth) {
	r.TrueCPUMeanMilli = gt.CPUMeanMilli
	r.TrueCPUP95Milli = gt.CPUP95Milli
	r.TrueCPUP99Milli = gt.CPUP99Milli
	r.TrueCPUMaxMilli = gt.CPUMaxMilli
	r.TrueMemMeanBytes = gt.MemoryMeanBytes
	r.TrueMemP95Bytes = gt.MemoryP95Bytes
	r.TrueMemP99Bytes = gt.MemoryP99Bytes
	r.TrueMemMaxBytes = gt.MemoryMaxBytes
}
